using System;

namespace Bliss.Gameplay.GameplayAbilitySystem
{
    public struct PredictionKey : IEquatable<PredictionKey>
    {
        /// <summary>
        /// The unique ID of this prediction key
        /// </summary>
        public short Current;
        /// <summary>
        /// If non 0, the original prediction key this was created from (in a dependency chain)
        /// </summary>
        public short Base;
        /// <summary>
        /// True if this was created as a server initiated activation key, used to identify server activations but cannot be used for prediction
        /// </summary>
        public bool IsServerInitiated;

        public bool PredictiveConnectionKey;

        /** A key is valid if it's non-zero, prediction keys for other clients will serialize down as 0 and be invalid */
        public bool IsValidKey() 
        {
            return Current > 0;
        }

        /** A key was generated by the local client if it's valid and not a server key, prediction keys for other clients will serialize down as 0 and be invalid */
        public bool IsLocalClientKey() 
        {
            return Current > 0 && !IsServerInitiated;
        }
        
        /// <summary>
        /// True if this was created as a server initiated activation key, used to identify server activations but cannot be used for prediction
        /// </summary>
        /// <returns></returns>
        public bool IsServerInitiatedKey()
        {
            return IsServerInitiated;
        }

        /// <summary>
        /// Can this key be used for more predictive actions, or has it already been sent off to the server?
        /// </summary>
        /// <returns></returns>
        public bool IsValidForMorePrediction()
        {
            return IsLocalClientKey();
        }
        
        /// <summary>
        /// Was this PredictionKey received from a NetSerialize or created locally?
        /// </summary>
        /// <returns></returns>
        bool WasReceived() 
        {
            return PredictiveConnectionKey;
        }
        
        bool WasLocallyGenerated()
        {
            return (Current > 0) && (!PredictiveConnectionKey);
        }
        
        public bool Equals(PredictionKey other)
        {
            // we're omitting Base here because it's not replicated
            return Current == other.Current  && IsServerInitiated == other.IsServerInitiated;
        }

        public override bool Equals(object obj)
        {
            return obj is PredictionKey other && Equals(other);
        }

        public override int GetHashCode()
        {
            return ((Current << 1) | (IsServerInitiated ? 1 : 0));
        }

        
        public PredictionKey CreateNewPredictionKey(AbilitySystemComponent owningComponent)
        {
            throw new NotImplementedException();
        }
        
        public PredictionKey CreateNewServerInitiatedKey(AbilitySystemComponent owningComponent)
        {
            throw new NotImplementedException();
        }

        public void GenerateDependentPredictionKey()
        {
            if (IsServerInitiated)
            {
                // Can't have dependent keys on server keys, use same key
                return;
            }

            short previous = Current;
            if (Base == 0)
            {
                Base = Current;
            }

            GenerateNewPredictionKey();

            if (previous > 0)
            {
                //TODO: Add Dependency
            }
        }
        
        private static short _generator = 1;
        private void GenerateNewPredictionKey()
        {
            Current = _generator++;
            if (_generator <= 0)
            {
                _generator = 1;
            }
        }
    }
}